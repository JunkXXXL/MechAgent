const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const html=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
const context={module:{exports:{}}};
vm.runInNewContext(html.match(/<script>([\s\S]*?)<\/script>/)[1],context);
const {analyze,isError,prune,pathsOf,essentialPaths,applyUpdate}=context.module.exports;
const folder=path.join(__dirname,'../../results/2026-10-16');
const dir=fs.readdirSync(folder).find(n=>fs.existsSync(path.join(folder,n,'1/trace.json')));
const data=JSON.parse(fs.readFileSync(path.join(folder,dir,'1/trace.json'),'utf8'));
const result=analyze(data);
assert.equal(result.events.length,29);
assert.equal(result.visits.length,8);
assert.equal(result.events.filter(e=>e.type==='model_input').length,7);
assert.equal(result.events.filter(e=>e.type==='code_check'&&isError(e)).length,2);
assert.equal(result.events.find(e=>e.sequence===11)._node,'code_execution_import_check');
assert.equal(result.visits[6].events.filter(e=>e.type==='model_input').length,0);
assert.equal(result.visits[2].events.filter(e=>e.type==='code_check').length,2);
assert.equal(result.visits[2].before.generation.code,data.events.find(e=>e.sequence===7).update.generation.code);
assert.equal(result.visits[3].before.error,'yes');
assert.equal(result.visits[7].before.error,'no');
assert.equal(result.visits[7].before.agent_code_history.length,7);
assert.equal(result.visits[7].before.agent_error_history.length,4);
assert.deepEqual(JSON.parse(JSON.stringify(applyUpdate(result.visits[7].before,result.visits[7].update))),data.final_state);
assert.equal(JSON.stringify(data),JSON.stringify(result.data));
const projected=prune(data,new Set(['events.*.response','final_state.generation.code']));
assert.ok(!('response' in projected.events[2]));
assert.ok(!('code' in projected.final_state.generation));
assert.equal(projected.events.length,29);
const defaults=essentialPaths(pathsOf(data));
assert.ok(defaults.has('events.*.response.generations.*.*.message.response_metadata'));
assert.ok(!defaults.has('final_state.generation.code'));
assert.equal(isError({type:'code_check',returncode:0,stderr:'warning'}),false);
assert.equal(isError({type:'node_update',update:{error:'no'}}),false);
assert.equal(isError({type:'code_check',error:'timeout'}),true);
assert.throws(()=>analyze({events:[null]}));
assert.throws(()=>analyze([]));
const partial=analyze({events:data.events.slice(0,3)});
assert.equal(partial.visits.length,1);
assert.equal(partial.visits[0].complete,false);
assert.equal(partial.visits[0].node,'input_classifier');
const odd=JSON.parse('{"__proto__":{"polluted":true},"events":[]}');
assert.equal(prune(odd,new Set()).__proto__.polluted,true);
assert.equal({}.polluted,undefined);
console.log('OK: real trace, LLM pairing, node visits, reducers, nested filters, errors, incomplete and invalid traces.');
